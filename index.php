<script>

document.addEventListener("DOMContentLoaded", function () {

    const slides = document.querySelectorAll(".rtc-banner-slide");

    const dots = document.querySelectorAll(".rtc-slider-dot");

    const nextButton = document.querySelector(".rtc-slider-next");

    const prevButton = document.querySelector(".rtc-slider-prev");

    let currentSlide = 0;

    let sliderInterval;


    function showSlide(index) {

        slides.forEach(function (slide) {

            slide.classList.remove("active");

        });


        dots.forEach(function (dot) {

            dot.classList.remove("active");

        });


        slides[index].classList.add("active");

        dots[index].classList.add("active");

        currentSlide = index;

    }


    function nextSlide() {

        currentSlide++;

        if (currentSlide >= slides.length) {

            currentSlide = 0;

        }

        showSlide(currentSlide);

    }


    function previousSlide() {

        currentSlide--;

        if (currentSlide < 0) {

            currentSlide = slides.length - 1;

        }

        showSlide(currentSlide);

    }


    nextButton.addEventListener("click", function () {

        nextSlide();

        restartSlider();

    });


    prevButton.addEventListener("click", function () {

        previousSlide();

        restartSlider();

    });


    dots.forEach(function (dot, index) {

        dot.addEventListener("click", function () {

            showSlide(index);

            restartSlider();

        });

    });


    function startSlider() {

        sliderInterval = setInterval(function () {

            nextSlide();

        }, 2500);

    }


    function restartSlider() {

        clearInterval(sliderInterval);

        startSlider();

    }


    startSlider();

});

</script>

