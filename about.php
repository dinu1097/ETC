<!-- Custom Vanilla JS Slider Logic -->
<script>
document.addEventListener("DOMContentLoaded", function () {
    const slides = document.querySelectorAll(".rtc-banner-slide");
    const dots = document.querySelectorAll(".rtc-slider-dot");
    const nextButton = document.querySelector(".rtc-slider-next");
    const prevButton = document.querySelector(".rtc-slider-prev");

    if (!slides.length) return;

    let currentSlide = 0;
    let sliderInterval;

    function showSlide(index) {
        slides.forEach(slide => slide.classList.remove("active"));
        dots.forEach(dot => dot.classList.remove("active"));

        slides[index].classList.add("active");
        if (dots[index]) dots[index].classList.add("active");
        currentSlide = index;
    }

    function nextSlide() {
        currentSlide = (currentSlide + 1) % slides.length;
        showSlide(currentSlide);
    }

    function previousSlide() {
        currentSlide = (currentSlide - 1 + slides.length) % slides.length;
        showSlide(currentSlide);
    }

    nextButton.addEventListener("click", function () {
        nextSlide();
        restartSlider();
    });

    prevButton.addEventListener("click", function () {
        previousSlide();
        restartSlider();
    });

    dots.forEach((dot, index) => {
        dot.addEventListener("click", function () {
            showSlide(index);
            restartSlider();
        });
    });

    function startSlider() {
        sliderInterval = setInterval(nextSlide, 3500);
    }

    function restartSlider() {
        clearInterval(sliderInterval);
        startSlider();
    }

    startSlider();
});
</script>

